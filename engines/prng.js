// Seeded pseudo-random numbers for the game generators. Same seed -> same sequence, on every
// machine and in every browser, so every student in a session gets the same puzzle (SPEC "Games").
// Pure module: no imports, no I/O. Never use Math.random() in engines/.

// 32-bit string hash (FNV-1a), so a seed can be any string, e.g. `${sessionSeed}:${gameIndex}`.
export function hashSeed(seed) {
  let h = 0x811c9dc5;
  const s = String(seed);
  for (let i = 0; i < s.length; i++) {
    h ^= s.charCodeAt(i);
    h = Math.imul(h, 0x01000193);
  }
  return h >>> 0;
}

// mulberry32: small, fast, good enough for shuffling and grid placement.
export function createRng(seed) {
  let a = typeof seed === 'number' ? seed >>> 0 : hashSeed(seed);
  const next = () => {
    a = (a + 0x6d2b79f5) >>> 0;
    let t = a;
    t = Math.imul(t ^ (t >>> 15), t | 1);
    t ^= t + Math.imul(t ^ (t >>> 7), t | 61);
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
  return {
    next, // [0, 1)
    int: (min, max) => min + Math.floor(next() * (max - min + 1)), // inclusive
    pick: (arr) => arr[Math.floor(next() * arr.length)],
    shuffle(arr) { // returns a new array (Fisher-Yates)
      const out = arr.slice();
      for (let i = out.length - 1; i > 0; i--) {
        const j = Math.floor(next() * (i + 1));
        [out[i], out[j]] = [out[j], out[i]];
      }
      return out;
    },
  };
}
